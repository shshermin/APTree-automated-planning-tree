namespace AIPlanning
{
    /// <summary>Whether a plan passed validation, and why not if it didn't.</summary>
    public sealed class PlanValidationResult
    {
        public bool IsValid { get; }
        public string Reason { get; }

        private PlanValidationResult(bool isValid, string reason)
        {
            IsValid = isValid;
            Reason = reason;
        }

        public static PlanValidationResult Valid() => new PlanValidationResult(true, null);
        public static PlanValidationResult Invalid(string reason) => new PlanValidationResult(false, reason);
    }

    /// <summary>
    /// Checks a plan right after a planning service produced it, before it is attached
    /// to the tree. Every ServicePlanning has one. Abstract because plans from a
    /// symbolic planner and plans generated by an LLM need different checks.
    /// </summary>
    public abstract class PlanValidator
    {
        /// <summary>Checks the planner's answer itself. Only a solved result passes by default.</summary>
        public virtual PlanValidationResult ValidateResult(PlanningResult result)
        {
            if (result == null)
                return PlanValidationResult.Invalid("No planning result");

            return result.EffectiveStatus switch
            {
                PlanStatus.Solved when result.Success => PlanValidationResult.Valid(),
                PlanStatus.Solved => PlanValidationResult.Invalid("Result is marked solved but not successful"),
                PlanStatus.Unsolvable => PlanValidationResult.Invalid($"Planner reports the problem as unsolvable: {result.Error}"),
                _ => PlanValidationResult.Invalid($"Planner error: {result.Error}")
            };
        }

        /// <summary>
        /// Checks the plan built from the result against the state it will run in.
        /// Must not change the blackboard.
        /// </summary>
        public abstract PlanValidationResult ValidatePlan(NodeGraph plan, Blackboard<FastName> blackboard);
    }
}
