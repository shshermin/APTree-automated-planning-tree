    if m:
        stick_num = int(m.group(1))
        parts = m.group(2).strip()
        # Split by double space to separate position and orientation
        pos_ori = re.split(r'\s{2,}', parts)
        position = pos_ori[0].strip()
        orientation = pos_ori[1].strip()
